"""Future WPI Forecasting Engine for AgriCost-AI.

Stage 7 Forecasting Module:
1. Ingests historical Financial Year (FY) series from data/processed/agricultural_inputs_wpi_fy_timeseries.csv.
2. Dynamically detects the latest observed financial year (2022-23, period_order=10).
3. Reuses the trained Ridge Regression pipeline (alpha=10.0) from models/trained/best_model.joblib
   WITHOUT retraining, modifying, or refitting preprocessing components.
4. Implements recursive multi-year forecasting for horizons 1 to 3 financial years:
   - h=1: FY 2023-24 (period_order=11)
   - h=2: FY 2024-25 (period_order=12)
   - h=3: FY 2025-26 (period_order=13)
5. Enforces rigorous recursive feature updates:
   - lag_1: Prior year's WPI (historical for h=1; predicted for h>1).
   - lag_2: Two years prior WPI (historical for h<=2; predicted for h>2).
   - rolling_mean_2: Two-year past moving average ((lag_1 + lag_2) / 2).
   - historical_pct_change: Prior percentage change (((lag_1 - lag_2) / lag_2) * 100).
   - period_order: Advances chronologically by 1 for each future step.
   - input_category: Preserves original categorical category indicator.
6. Strictly validates against invalid commodity codes, out-of-range horizons, non-positive forecasts,
   and prevents any target leakage.
7. Preserves the 'WPI index points' unit semantics (never rupees).
8. Integrates seamlessly with src.budget.estimate_future_input_price using the ratio bridge formula.
9. Documents recursive error accumulation, uncertainty compounding, and temporal baseline caveats.
"""

