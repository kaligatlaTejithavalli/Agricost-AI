def run_forecast_pipeline(
    forecast_horizon: int = 3,
    output_dir: Optional[Path] = None,
) -> Dict[str, Any]:
    """Execute the end-to-end forecasting pipeline for all 26 commodities and serialize outputs.

    Args:
        forecast_horizon: Maximum horizon in annual steps (1 to 3).
        output_dir: Optional directory to save output artifacts. Defaults to models/evaluation/forecasts/.

    Returns:
        Dict[str, Any] containing metadata, file paths, and summary statistics.
    """
    out_dir = Path(output_dir) if output_dir else FORECASTS_DIR
    out_dir.mkdir(parents=True, exist_ok=True)

    # 1. Generate consolidated forecasts for all 26 commodities
    forecasts_df = forecast_all_commodities(forecast_horizon=forecast_horizon)
    csv_path = out_dir / "commodity_forecasts_all.csv"
    forecasts_df.to_csv(csv_path, index=False)

    # 2. Extract specific examples for reporting: Urea, DAP, HSD (Diesel)
    example_codes = {
        "urea": 1310020001,
        "dap": 1310020002,
        "diesel_hsd": 1202000005,
    }
    examples_summary = {}
    for key, code in example_codes.items():
        res = forecast_commodity(commodity_code=code, forecast_horizon=forecast_horizon)
        examples_summary[key] = res.to_dict()

    summary_json_path = out_dir / "forecasts_summary.json"
    with open(summary_json_path, "w", encoding="utf-8") as f:
        json.dump(examples_summary, f, indent=2)

    # 3. Save methodology and limitations markdown
    doc_path = save_forecast_methodology_doc(out_dir)

    # 4. Save metadata JSON
    metadata = {
        "model_name": "Ridge Regression (alpha=10.0)",
        "model_artifact": "models/trained/best_model.joblib",
        "total_commodities_supported": len(AGRICULTURAL_INPUT_CATALOG),
        "latest_observed_financial_year": "2022-23",
        "latest_observed_order": 10,
        "forecast_horizons_generated": list(range(1, forecast_horizon + 1)),
        "forecast_periods_generated": [advance_financial_year("2022-23", s) for s in range(1, forecast_horizon + 1)],
        "total_forecast_records": len(forecasts_df),
        "target_unit": TARGET_LABEL,
        "base_year": BASE_YEAR_LABEL,
        "artifacts_saved": {
            "all_forecasts_csv": str(csv_path),
            "examples_summary_json": str(summary_json_path),
            "methodology_doc": str(doc_path),
        },
    }
    metadata_json_path = out_dir / "forecast_metadata.json"
    with open(metadata_json_path, "w", encoding="utf-8") as f:
        json.dump(metadata, f, indent=2)

    return {
        "metadata": metadata,
        "forecasts_df": forecasts_df,
        "examples": examples_summary,
        "artifacts": metadata["artifacts_saved"],
    }


