def forecast_commodity(
    commodity_code: int,
    forecast_horizon: int = 3,
    pipeline: Optional[Pipeline] = None,
    timeseries_path: Optional[Path] = None,
    test_rmse: float = DEFAULT_HISTORICAL_RMSE,
) -> CommodityForecastResult:
    """Generate recursive multi-year WPI index forecasts for a selected agricultural commodity.

    Args:
        commodity_code: Integer commodity code from AGRICULTURAL_INPUT_CATALOG.
        forecast_horizon: Number of annual forecast steps (1 to 3).
        pipeline: Optional pre-loaded Pipeline. If None, loads best_model.joblib.
        timeseries_path: Optional path to processed historical timeseries.
        test_rmse: Historical benchmark RMSE used for indicative dispersion intervals.

    Returns:
        CommodityForecastResult: Structured forecast object with per-year details and disclaimers.

    Raises:
        ValueError: If commodity_code is invalid, horizon is outside 1..3, or model generates non-positive WPI.
    """
    # 1. Validate forecast horizon
    if not isinstance(forecast_horizon, int) or isinstance(forecast_horizon, bool):
        raise ValueError(f"Forecast horizon must be an integer, got {type(forecast_horizon).__name__}.")

    if forecast_horizon < 1 or forecast_horizon > MAX_FORECAST_HORIZON:
        raise ValueError(
            f"Unsupported forecast horizon: {forecast_horizon}. "
            f"Supported horizons are 1 to {MAX_FORECAST_HORIZON} financial years."
        )

    # 2. Load historical series & pipeline
    history_df = load_historical_commodity_series(commodity_code, timeseries_path=timeseries_path)
    if pipeline is None:
        pipeline = load_forecasting_pipeline()

    # 3. Dynamic detection of latest observed point (never hard-coded)
    last_row = history_df.iloc[-1]
    last_observed_period = str(last_row["period_label"])
    last_observed_order = int(last_row["period_order"])
    last_observed_wpi = float(last_row["wpi_index_points"])

    # Metadata lookup
    meta = AGRICULTURAL_INPUT_CATALOG[int(commodity_code)]
    commodity_name = meta.name
    input_category = meta.category
    suggested_unit = meta.suggested_unit

    # Check that history has at least 2 consecutive periods for initial lags
    if len(history_df) < 2:
        raise ValueError(
            f"Insufficient historical observations for commodity {commodity_code}: "
            f"Found {len(history_df)}, expected at least 2 consecutive years."
        )

    second_last_row = history_df.iloc[-2]
    second_last_wpi = float(second_last_row["wpi_index_points"])

    # 4. Recursive Forecasting Loop
    forecast_steps: List[SingleYearForecast] = []

    # Current running lags initialized from actual historical observations
    current_lag_1 = last_observed_wpi
    current_lag_2 = second_last_wpi
    current_order = last_observed_order
    prior_step_pred = last_observed_wpi

    for step in range(1, forecast_horizon + 1):
        target_period = advance_financial_year(last_observed_period, step=step)
        target_order = current_order + 1

        # Calculate momentum and rolling features strictly from the two preceding points
        pct_change = ((current_lag_1 - current_lag_2) / current_lag_2) * 100.0
        rolling_mean = (current_lag_1 + current_lag_2) / 2.0

        # Construct single-row feature DataFrame strictly matching trained pipeline schema
        feature_dict = {
            "lag_1": current_lag_1,
            "lag_2": current_lag_2,
            "historical_pct_change": pct_change,
            "rolling_mean_2": rolling_mean,
            "period_order": target_order,
            "input_category": input_category,
        }
        input_row_df = pd.DataFrame([feature_dict])

        # Predict one step ahead using the fitted Ridge pipeline
        raw_pred = float(pipeline.predict(input_row_df)[0])

        # Validation: WPI must be finite and positive. If non-positive, reject as invalid rather than fabricating.
        if math.isnan(raw_pred) or math.isinf(raw_pred):
            raise ValueError(f"Model generated non-finite prediction '{raw_pred}' for period {target_period}.")

        if raw_pred <= 0.0:
            raise ValueError(
                f"Model generated non-positive WPI prediction ({raw_pred:.2f} index points) "
                f"for commodity {commodity_name} in {target_period}. WPI cannot be zero or negative."
            )

        # Percentage change metrics
        pct_vs_last_observed = ((raw_pred - last_observed_wpi) / last_observed_wpi) * 100.0
        pct_vs_prior_year = ((raw_pred - prior_step_pred) / prior_step_pred) * 100.0

        # Indicative uncertainty interval: compounding dispersion sigma_h = RMSE * sqrt(h)
        # 80% two-sided normal approximation: z = 1.28
        sigma_h = test_rmse * math.sqrt(step)
        z_80 = 1.28155
        lower_80 = max(0.1, raw_pred - (z_80 * sigma_h))
        upper_80 = raw_pred + (z_80 * sigma_h)

        step_forecast = SingleYearForecast(
            horizon=step,
            forecast_period=target_period,
            period_order=target_order,
            lag_1=current_lag_1,
            lag_2=current_lag_2,
            rolling_mean_2=rolling_mean,
            historical_pct_change=pct_change,
            forecast_wpi=raw_pred,
            pct_change_vs_last_observed=pct_vs_last_observed,
            pct_change_vs_prior_year=pct_vs_prior_year,
            target_unit=TARGET_LABEL,
            is_forecast=True,
            indicative_lower_80=lower_80,
            indicative_upper_80=upper_80,
            static_baseline_wpi=last_observed_wpi,
        )
        forecast_steps.append(step_forecast)

        # Update recursive state for the next future step
        current_lag_2 = current_lag_1
        current_lag_1 = raw_pred
        current_order = target_order
        prior_step_pred = raw_pred

    result = CommodityForecastResult(
        commodity_code=int(commodity_code),
        commodity_name=commodity_name,
        input_category=input_category,
        suggested_unit=suggested_unit,
        last_observed_period=last_observed_period,
        last_observed_order=last_observed_order,
        last_observed_wpi=last_observed_wpi,
        forecast_horizon=forecast_horizon,
        forecasts=forecast_steps,
        model_name="Ridge Regression (alpha=10.0)",
        historical_cutoff=last_observed_period,
        target_unit=TARGET_LABEL,
        base_year=BASE_YEAR_LABEL,
    )
    return result


def forecast_all_commodities(
    forecast_horizon: int = 3,
    pipeline: Optional[Pipeline] = None,
    timeseries_path: Optional[Path] = None,
) -> pd.DataFrame:
    """Generate recursive forecasts across all 26 verified agricultural input commodities.

    Returns:
        pd.DataFrame containing 26 commodities * forecast_horizon rows.
    """
    if pipeline is None:
        pipeline = load_forecasting_pipeline()

    all_dfs = []
    for code in sorted(AGRICULTURAL_INPUT_CATALOG.keys()):
        res = forecast_commodity(
            commodity_code=code,
            forecast_horizon=forecast_horizon,
            pipeline=pipeline,
            timeseries_path=timeseries_path,
        )
        all_dfs.append(res.to_dataframe())

    combined_df = pd.concat(all_dfs, ignore_index=True)
    return combined_df


