def bridge_forecast_to_budget(
    forecast_result: CommodityForecastResult,
    target_period: str,
    current_user_price: float,
    price_unit: str,
    user_price_year: Optional[str] = None,
) -> PriceProjectionResult:
    """Bridge a forecasted WPI point to a user-supplied current rupee price.

    Uses the verified ratio bridge formula from src.budget.estimate_future_input_price:
        Estimated Future Price (Rs) = User Price (Rs) * (Forecast WPI / Current WPI)

    Args:
        forecast_result: CommodityForecastResult generated by forecast_commodity().
        target_period: Future period to evaluate (e.g. '2023-24', '2024-25', '2025-26').
        current_user_price: Positive rupee price paid currently by user.
        price_unit: Physical purchase unit (e.g., 'Rs per 50 kg bag').
        user_price_year: Optional year associated with the user's current price.

    Returns:
        PriceProjectionResult from src.budget.

    Raises:
        ValueError: If target_period is not in the forecast result or inputs are invalid.
    """
    # Find matching forecast period
    matching_steps = [f for f in forecast_result.forecasts if f.forecast_period == target_period]
    if not matching_steps:
        available_periods = [f.forecast_period for f in forecast_result.forecasts]
        raise ValueError(
            f"Target period '{target_period}' not found in forecast result. "
            f"Available forecast periods: {available_periods}."
        )

    target_step = matching_steps[0]

    # Invoke budget ratio bridge
    projection = estimate_future_input_price(
        current_wpi=forecast_result.last_observed_wpi,
        forecast_wpi=target_step.forecast_wpi,
        current_user_price=current_user_price,
        price_unit=price_unit,
        commodity_code=forecast_result.commodity_code,
        commodity_name=forecast_result.commodity_name,
        current_period=forecast_result.last_observed_period,
        forecast_period=target_step.forecast_period,
        series_type="FY",
        forecast_commodity_code=forecast_result.commodity_code,
        forecast_series_type="FY",
    )

    return projection


def bridge_dual_forecast_to_budget(
    forecast_result: CommodityForecastResult,
    target_period: str,
    current_user_price: float,
    price_unit: str,
    user_price_year: Optional[str] = None,
) -> Dict[str, PriceProjectionResult]:
    """Bridge both ML Trend (Ridge) and Static Baseline forecasts to user-supplied rupee prices.

    Uses the verified WPI-to-rupee ratio bridge formula:
        Estimated Future Price (₹) = Current Price (₹) * (Forecast WPI / Current WPI)

    Returns:
        Dict[str, PriceProjectionResult] containing:
            'ml_trend': Projection using the Ridge Regression forecast.
            'static_baseline': Projection using the static baseline (unchanged WPI).
    """
    # 1. Primary ML Trend Projection (Ridge)
    ml_projection = bridge_forecast_to_budget(
        forecast_result=forecast_result,
        target_period=target_period,
        current_user_price=current_user_price,
        price_unit=price_unit,
        user_price_year=user_price_year,
    )

    # 2. Static Baseline Projection (last observed WPI carried forward unchanged)
    static_projection = estimate_future_input_price(
        current_wpi=forecast_result.last_observed_wpi,
        forecast_wpi=forecast_result.last_observed_wpi,  # Flat baseline: zero index movement
        current_user_price=current_user_price,
        price_unit=price_unit,
        commodity_code=forecast_result.commodity_code,
        commodity_name=forecast_result.commodity_name,
        current_period=forecast_result.last_observed_period,
        forecast_period=target_period,
        series_type="FY",
        forecast_commodity_code=forecast_result.commodity_code,
        forecast_series_type="FY",
    )

    return {
        "ml_trend": ml_projection,
        "static_baseline": static_projection,
    }


