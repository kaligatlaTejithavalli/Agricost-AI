        "- **Horizon 3 (FY 2025-26):**\n"
        "  - `lag_1` = Predicted y_hat(2024-25)\n"
        "  - `lag_2` = Predicted y_hat(2023-24)\n"
        "  - `rolling_mean_2` = (y_hat(2024-25) + y_hat(2023-24)) / 2\n"
        "  - `historical_pct_change` = ((y_hat(2024-25) - y_hat(2023-24)) / y_hat(2023-24)) * 100\n"
