@dataclass(frozen=True)
class SingleYearForecast:
    """Individual annual step in a recursive multi-year forecast."""

    horizon: int
    forecast_period: str
    period_order: int
    lag_1: float
    lag_2: float
    rolling_mean_2: float
    historical_pct_change: float
    forecast_wpi: float
    pct_change_vs_last_observed: float
    pct_change_vs_prior_year: float
    target_unit: str = TARGET_LABEL
    is_forecast: bool = True
    indicative_lower_80: Optional[float] = None
    indicative_upper_80: Optional[float] = None
    static_baseline_wpi: Optional[float] = None

    def to_dict(self) -> Dict[str, Any]:
        """Convert single forecast step to dictionary."""
        return {
            "horizon": self.horizon,
            "forecast_period": self.forecast_period,
            "period_order": self.period_order,
            "lag_1": round(self.lag_1, 2),
            "lag_2": round(self.lag_2, 2),
            "rolling_mean_2": round(self.rolling_mean_2, 2),
            "historical_pct_change": round(self.historical_pct_change, 2),
            "forecast_wpi": round(self.forecast_wpi, 2),
            "static_baseline_wpi": round(self.static_baseline_wpi, 2) if self.static_baseline_wpi is not None else None,
            "pct_change_vs_last_observed": round(self.pct_change_vs_last_observed, 2),
            "pct_change_vs_prior_year": round(self.pct_change_vs_prior_year, 2),
            "target_unit": self.target_unit,
            "is_forecast": self.is_forecast,
            "indicative_lower_80": round(self.indicative_lower_80, 2) if self.indicative_lower_80 is not None else None,
            "indicative_upper_80": round(self.indicative_upper_80, 2) if self.indicative_upper_80 is not None else None,
        }


@dataclass(frozen=True)
class CommodityForecastResult:
    """Comprehensive forecasting output for an agricultural input commodity."""

    commodity_code: int
    commodity_name: str
    input_category: str
    suggested_unit: str
    last_observed_period: str
    last_observed_order: int
    last_observed_wpi: float
    forecast_horizon: int
    forecasts: List[SingleYearForecast]
    model_name: str = "Ridge Regression (alpha=10.0)"
    historical_cutoff: str = "2022-23"
    target_unit: str = TARGET_LABEL
    base_year: str = BASE_YEAR_LABEL
    disclaimer_uncertainty: str = FORECAST_UNCERTAINTY_DISCLAIMER
    disclaimer_temporal: str = DATA_CUTOFF_AND_TEMPORAL_DISCLAIMER

    def to_dict(self) -> Dict[str, Any]:
        """Convert full forecast result to dictionary."""
        return {
            "commodity_code": self.commodity_code,
            "commodity_name": self.commodity_name,
            "input_category": self.input_category,
            "suggested_unit": self.suggested_unit,
            "last_observed_period": self.last_observed_period,
            "last_observed_order": self.last_observed_order,
            "last_observed_wpi": round(self.last_observed_wpi, 2),
            "forecast_horizon": self.forecast_horizon,
            "model_name": self.model_name,
            "historical_cutoff": self.historical_cutoff,
            "target_unit": self.target_unit,
            "base_year": self.base_year,
            "forecasts": [f.to_dict() for f in self.forecasts],
            "disclaimer_uncertainty": self.disclaimer_uncertainty,
            "disclaimer_temporal": self.disclaimer_temporal,
        }

    def to_dataframe(self) -> pd.DataFrame:
        """Export forecast steps to a tabular DataFrame."""
        rows = []
        for f in self.forecasts:
            row = {
                "commodity_code": self.commodity_code,
                "commodity_name": self.commodity_name,
                "input_category": self.input_category,
                "last_observed_period": self.last_observed_period,
                "last_observed_wpi": round(self.last_observed_wpi, 2),
                "forecast_horizon": f.horizon,
                "forecast_period": f.forecast_period,
                "period_order": f.period_order,
                "forecast_wpi": round(f.forecast_wpi, 2),
                "static_baseline_wpi": round(f.static_baseline_wpi, 2) if f.static_baseline_wpi is not None else round(self.last_observed_wpi, 2),
                "pct_change_vs_last_observed": round(f.pct_change_vs_last_observed, 2),
                "pct_change_vs_prior_year": round(f.pct_change_vs_prior_year, 2),
                "lag_1": round(f.lag_1, 2),
                "lag_2": round(f.lag_2, 2),
                "rolling_mean_2": round(f.rolling_mean_2, 2),
                "historical_pct_change": round(f.historical_pct_change, 2),
                "target_unit": self.target_unit,
                "indicative_lower_80": round(f.indicative_lower_80, 2) if f.indicative_lower_80 is not None else None,
                "indicative_upper_80": round(f.indicative_upper_80, 2) if f.indicative_upper_80 is not None else None,
                "model_name": self.model_name,
            }
            rows.append(row)
        return pd.DataFrame(rows)


