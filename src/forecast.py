def advance_financial_year(current_fy: str, step: int = 1) -> str:
    """Advance a financial year label by an integer number of annual periods.

    Example:
        advance_financial_year("2022-23", 1) -> "2023-24"
        advance_financial_year("2022-23", 2) -> "2024-25"
        advance_financial_year("2022-23", 3) -> "2025-26"
    """
    pattern = r"^(\d{4})-(\d{2})$"
    match = re.match(pattern, current_fy.strip())
    if not match:
        raise ValueError(
            f"Invalid financial year format '{current_fy}'. Expected format 'YYYY-YY' (e.g. '2022-23')."
        )

    start_year = int(match.group(1))
    target_start = start_year + step
    target_end = target_start + 1
    end_str = f"{target_end % 100:02d}"
    return f"{target_start}-{end_str}"


def load_historical_commodity_series(
    commodity_code: int,
    timeseries_path: Optional[Path] = None,
) -> pd.DataFrame:
    """Load and validate the historical Financial Year WPI series for a specific commodity.

    Args:
        commodity_code: Integer DPIIT commodity code.
        timeseries_path: Optional path to agricultural_inputs_wpi_fy_timeseries.csv.

    Returns:
        pd.DataFrame sorted chronologically by period_order.

    Raises:
        ValueError: If commodity_code is invalid or not in catalog.
        FileNotFoundError: If processed timeseries file is missing.
    """
    try:
        code_int = int(commodity_code)
    except (ValueError, TypeError):
        raise ValueError(f"Commodity code must be an integer, got: '{commodity_code}'.")

    if code_int not in AGRICULTURAL_INPUT_CATALOG:
        available_codes = sorted(AGRICULTURAL_INPUT_CATALOG.keys())
        raise ValueError(
            f"Commodity code {code_int} is not a verified agricultural input commodity. "
            f"Must be one of the 26 verified codes: {available_codes}."
        )

    path = Path(timeseries_path) if timeseries_path else PROCESSED_DATA_DIR / "agricultural_inputs_wpi_fy_timeseries.csv"
    if not path.exists():
        raise FileNotFoundError(f"Processed timeseries file not found at: {path}")

    df = pd.read_csv(path)
    series_df = df[df["commodity_code"] == code_int].copy()

    if series_df.empty:
        raise ValueError(f"No historical records found for commodity code {code_int} in {path.name}.")

    series_df = series_df.sort_values(by="period_order").reset_index(drop=True)
    return series_df


def load_forecasting_pipeline(model_path: Optional[Path] = None) -> Pipeline:
    """Load the existing serialized Ridge Regression model pipeline without retraining."""
    path = Path(model_path) if model_path else TRAINED_MODELS_DIR / "best_model.joblib"
    if not path.exists():
        raise FileNotFoundError(f"Trained model artifact not found at: {path}")

    pipeline = joblib.load(path)
    if not isinstance(pipeline, Pipeline):
        raise TypeError(f"Expected scikit-learn Pipeline, got {type(pipeline).__name__}.")

    return pipeline


